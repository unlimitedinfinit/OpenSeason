use chrono::Utc;
use serde_json::json;
use std::path::Path;

use super::types::{WorkflowPlan, WorkflowStep, WorkflowStepStatus};
use crate::case_profile::CaseProfile;

/// Formulates a structured, multi-step workflow plan to achieve a specific self-help objective.
pub fn plan_workflow(case_dir: &Path, profile: &CaseProfile, objective: &str) -> WorkflowPlan {
    let obj_lower = objective.trim().to_ascii_lowercase();
    let plan_id = format!("plan-{}", uuid::Uuid::new_v4().to_string().chars().take(8).collect::<String>());
    let now = Utc::now().to_rfc3339();

    let steps = if obj_lower.contains("transcript") || obj_lower.contains("missing record") || obj_lower.contains("docket sheet") {
        vec![
            WorkflowStep {
                id: "step-1-inventory".into(),
                title: "Scan Record Inventory & Check Evidentiary Gaps".into(),
                description: "Scan local orders, filings, evidence, and drafts to catalog verified provenance.".into(),
                tool_command: "record_inventory".into(),
                params: json!({"path": case_dir.to_string_lossy()}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: false,
                approval_prompt: None,
                approval_granted: false,
                verification_criteria: "Complete 4-tier inventory generated with SHA-256 hashes.".into(),
                receipt_ref: None,
                output_summary: None,
            },
            WorkflowStep {
                id: "step-2-court-rules".into(),
                title: "Retrieve Court Records Access Rules & Fee Schedule".into(),
                description: "Discover clerk counter hours, statutory copy fees, and electronic portals for the jurisdiction.".into(),
                tool_command: "court_access_profile".into(),
                params: json!({"query": if profile.governing_state.is_empty() { &profile.court.name } else { &profile.governing_state }}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: false,
                approval_prompt: None,
                approval_granted: false,
                verification_criteria: "Court access profile resolved with transcript request procedures.".into(),
                receipt_ref: None,
                output_summary: None,
            },
            WorkflowStep {
                id: "step-3-request-form".into(),
                title: "Generate Official Records Request Form".into(),
                description: "Create prefilled records request form (e.g. NJ Form CN 10200 or CO JDF 4) with itemized missing items.".into(),
                tool_command: "record_retrieval_execute".into(),
                params: json!({"path": case_dir.to_string_lossy()}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: true,
                approval_prompt: Some("Review requested records list and statutory fee estimate before submitting to the clerk.".into()),
                approval_granted: false,
                verification_criteria: "Records request packet rendered and 14-day clerk follow-up task registered.".into(),
                receipt_ref: None,
                output_summary: None,
            },
        ]
    } else if obj_lower.contains("extension") || obj_lower.contains("enlargement") || obj_lower.contains("more time") {
        vec![
            WorkflowStep {
                id: "step-1-extension-assess".into(),
                title: "Audit Case Baseline & Formulate Extension Grounds".into(),
                description: "Inspect case record completeness and generate tailored good cause grounds (e.g. transcript delays, record assembly).".into(),
                tool_command: "extension_suggest".into(),
                params: json!({"path": case_dir.to_string_lossy()}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: false,
                approval_prompt: None,
                approval_granted: false,
                verification_criteria: "Extension route and grounds formulated.".into(),
                receipt_ref: None,
                output_summary: None,
            },
            WorkflowStep {
                id: "step-2-conferral-letter".into(),
                title: "Prepare Opposing Counsel Conferral & Consent Request".into(),
                description: "Draft professional conferral inquiry under local rules (e.g. NJ R. 2:6-11(f) / CO C.A.R. 31(a)) for automatic 30-day consent.".into(),
                tool_command: "extension_suggest".into(),
                params: json!({"path": case_dir.to_string_lossy()}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: true,
                approval_prompt: Some("Review conferral letter before sending to opposing counsel or pro se parties.".into()),
                approval_granted: false,
                verification_criteria: "Conferral letter reviewed by user.".into(),
                receipt_ref: None,
                output_summary: None,
            },
            WorkflowStep {
                id: "step-3-formal-motion".into(),
                title: "Prepare Formal Motion for Enlargement of Time (Backup / Unopposed)".into(),
                description: "Generate court-ready formal motion (NJ Form CN 10503 / CO JDF 1314) with sworn good-cause certification.".into(),
                tool_command: "extension_evaluate".into(),
                params: json!({"path": case_dir.to_string_lossy(), "target": "Brief / Responsive Pleading", "days": 30, "consent": false}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: true,
                approval_prompt: Some("Export formal motion for enlargement of time to exports/ folder?".into()),
                approval_granted: false,
                verification_criteria: "Motion for enlargement exported and ready to file.".into(),
                receipt_ref: None,
                output_summary: None,
            },
        ]
    } else if obj_lower.contains("appeal") || obj_lower.contains("notice of appeal") {
        vec![
            WorkflowStep {
                id: "step-1-decode-order".into(),
                title: "Decode Operative Final Judgment / Dismissal Order".into(),
                description: "Extract entry date, signer, and candidate response windows from the appealed order.".into(),
                tool_command: "order_decode".into(),
                params: json!({}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: false,
                approval_prompt: None,
                approval_granted: false,
                verification_criteria: "Entry date and operative dismissal clauses isolated without guessing.".into(),
                receipt_ref: None,
                output_summary: None,
            },
            WorkflowStep {
                id: "step-2-mail-audit".into(),
                title: "Audit Postmark vs Clerk Receipt Jurisdictional Gaps".into(),
                description: "Audit transmission delay against jurisdictional rules (e.g., Colorado Physical Clerk Receipt Rule).".into(),
                tool_command: "timeline_audit_mail".into(),
                params: json!({"path": case_dir.to_string_lossy(), "order_date": profile.created_at.chars().take(10).collect::<String>()}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: false,
                approval_prompt: None,
                approval_granted: false,
                verification_criteria: "Jurisdictional traps flagged and mailing delays computed.".into(),
                receipt_ref: None,
                output_summary: None,
            },
            WorkflowStep {
                id: "step-3-check-venue".into(),
                title: "Verify Venue Competence & Prescribed Notice Requirements".into(),
                description: "Check certification requirements, caption formatting, and non-alterable appeal clock rules.".into(),
                tool_command: "check_venue".into(),
                params: json!({"path": case_dir.to_string_lossy()}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: false,
                approval_prompt: None,
                approval_granted: false,
                verification_criteria: "All venue and verification checklist rules evaluated.".into(),
                receipt_ref: None,
                output_summary: None,
            },
            WorkflowStep {
                id: "step-4-draft-notice".into(),
                title: "Review Notice of Appeal Drafting & Caption".into(),
                description: "Ensure parties, trial court docket, judgment date, and user text match court rules.".into(),
                tool_command: "draft_preview".into(),
                params: json!({"path": case_dir.to_string_lossy()}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: true,
                approval_prompt: Some("Verify that all party names, court designations, and dates are completely accurate before export.".into()),
                approval_granted: false,
                verification_criteria: "Human verifies caption and confirms no placeholder text exists.".into(),
                receipt_ref: None,
                output_summary: None,
            },
            WorkflowStep {
                id: "step-5-export-court".into(),
                title: "Export Court-Formatted Notice of Appeal (Word + PDF)".into(),
                description: "Generate court-ready pleading files following exact court margin and typography rules.".into(),
                tool_command: "export_court".into(),
                params: json!({"path": case_dir.to_string_lossy(), "kind": "notice_of_appeal"}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: true,
                approval_prompt: Some("Export court papers to exports/ folder? Reminder: You must file and serve your own document.".into()),
                approval_granted: false,
                verification_criteria: "PDF and DOCX exports generated under exports/.".into(),
                receipt_ref: None,
                output_summary: None,
            },
        ]
    } else {
        // Universal Legal Self-Help Roadmap
        vec![
            WorkflowStep {
                id: "step-1-audit".into(),
                title: "Reconstruct Official Case Record & Inventory".into(),
                description: "Classify all case materials into official filings, transcripts, and personal drafts.".into(),
                tool_command: "record_inventory".into(),
                params: json!({"path": case_dir.to_string_lossy()}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: false,
                approval_prompt: None,
                approval_granted: false,
                verification_criteria: "Inventory complete with verified file provenance.".into(),
                receipt_ref: None,
                output_summary: None,
            },
            WorkflowStep {
                id: "step-2-deadlines".into(),
                title: "Calculate Governing Procedural Deadlines & Tolling".into(),
                description: "Compute response window using dated rules packs, holiday rollover, and state tolling rules.".into(),
                tool_command: "case_next_steps".into(),
                params: json!({"path": case_dir.to_string_lossy()}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: false,
                approval_prompt: None,
                approval_granted: false,
                verification_criteria: "Procedural branches and strict deadlines calculated.".into(),
                receipt_ref: None,
                output_summary: None,
            },
            WorkflowStep {
                id: "step-3-draft-review".into(),
                title: "Human Review of Draft & Factual Grounding".into(),
                description: "Cross-check draft assertions against verified exhibits and ensure no placeholder text remains.".into(),
                tool_command: "check_all".into(),
                params: json!({"path": case_dir.to_string_lossy()}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: true,
                approval_prompt: Some("Carefully review the motion draft. Confirm all facts match the evidence before packet assembly.".into()),
                approval_granted: false,
                verification_criteria: "All fact-check items grounded in record exhibits.".into(),
                receipt_ref: None,
                output_summary: None,
            },
            WorkflowStep {
                id: "step-4-assemble".into(),
                title: "Assemble Complete Submission Packet".into(),
                description: "Compile notice of motion, user motion, sworn certification, proposed order, and service proof.".into(),
                tool_command: "export_packet".into(),
                params: json!({"path": case_dir.to_string_lossy()}),
                status: WorkflowStepStatus::Pending,
                requires_human_approval: true,
                approval_prompt: Some("Assemble and export final court filing packet?".into()),
                approval_granted: false,
                verification_criteria: "Five-part packet exported to Word and PDF.".into(),
                receipt_ref: None,
                output_summary: None,
            },
        ]
    };

    let total = steps.len();
    WorkflowPlan {
        id: plan_id,
        case_id: profile.id.clone(),
        objective: objective.trim().to_string(),
        created_at: now.clone(),
        updated_at: now,
        steps,
        current_step_index: 0,
        is_complete: false,
        summary: format!("Formulated {}-step action workflow for objective: '{}'.", total, objective),
    }
}
